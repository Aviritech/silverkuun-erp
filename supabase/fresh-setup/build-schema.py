#!/usr/bin/env python3
"""Builds 01-schema.sql: every migration in supabase/migrations, in order, as one file for a brand-new project.

Enum values that later migrations add with `alter type ... add value` are folded into the original
`create type`, because Postgres will not use a value added in the same transaction, and the Supabase SQL
Editor runs a pasted script as one transaction. Re-run this after adding a migration:
    python3 supabase/fresh-setup/build-schema.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MIGRATIONS = ROOT.parent / "migrations"

REPLACE = {
    "create type public.member_status as enum ('draft', 'pending_approval', 'returned', 'approved');":
    "create type public.member_status as enum ('draft', 'with_marketer', 'marketer_reviewed', 'pending_approval', 'returned', 'approved');",
    "  'kyc_form', 'nin_slip', 'means_of_id', 'utility_bill', 'passport_photo', 'signed_agreement_letter', 'other'\n);":
    "  'kyc_form', 'nin_slip', 'means_of_id', 'utility_bill', 'passport_photo', 'signed_agreement_letter', 'other',\n"
    "  'statement_of_account', 'maturity_letter'\n);",
    "  'draft', 'submitted', 'appraised', 'returned', 'rejected', 'approved', 'active', 'closed', 'cancelled'\n);":
    "  'draft', 'submitted', 'appraised', 'credit_approved', 'returned', 'rejected', 'approved', 'active', 'closed', 'cancelled'\n);",
}

parts = []
files = sorted(MIGRATIONS.glob("*.sql"))
for f in files:
    sql = f.read_text()
    for old, new in REPLACE.items():
        sql = sql.replace(old, new)
    lines = [
        ("-- (folded into create type above) " + l) if "alter type" in l and " add value " in l else l
        for l in sql.splitlines()
    ]
    parts.append(f"\n-- {'=' * 100}\n-- {f.name}\n-- {'=' * 100}\n\n" + "\n".join(lines) + "\n")

remaining = [l for p in parts for l in p.splitlines() if " add value " in l and not l.startswith("--")]
assert not remaining, f"unfolded enum additions: {remaining}"
for old in REPLACE:
    assert sum(old in f.read_text() for f in files) == 1, f"expected exactly one match for: {old[:60]}"

header = f"""-- Silverkuun ERP: complete database schema for a NEW, EMPTY Supabase project.
-- Generated by supabase/fresh-setup/build-schema.py from {len(files)} migrations
-- ({files[0].name} .. {files[-1].name}). Do not edit by hand.
--
-- Creates every table, type, function, trigger, RLS policy, role/permission and storage bucket, plus the
-- reference data the app needs (departments, roles, permissions, plan types and rates, loan products,
-- CBN bank list, chart of accounts, posting rules, HR leave types and job titles).
-- It contains no regions, branches, staff or members: load those with the seed scripts.
--
-- Run it once, on an empty project. It is not safe to run twice.

"""
(ROOT / "01-schema.sql").write_text(header + "".join(parts))
print(f"wrote 01-schema.sql from {len(files)} migrations")
